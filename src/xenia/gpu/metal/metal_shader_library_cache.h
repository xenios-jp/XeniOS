#ifndef XENIA_GPU_METAL_METAL_SHADER_LIBRARY_CACHE_H_
#define XENIA_GPU_METAL_METAL_SHADER_LIBRARY_CACHE_H_

#include <cstdint>
#include <cstdio>
#include <filesystem>
#include <mutex>
#include <string>
#include <unordered_map>
#include <vector>

#include "xenia/gpu/shader.h"
#include "xenia/gpu/spirv_shader.h"

namespace xe {
namespace gpu {
namespace metal {

// The Metal libraries a title's guest shaders were translated to, kept on disk
// so a later launch loads them instead of translating the guest microcode again
// (to SPIR-V, then to AIR). Each record also holds the shader's texture and
// sampler bindings, the only other result of the translation that draws read,
// so a hit skips the translation entirely. The shader storage only keeps the
// microcode and the pipeline descriptions, which every backend shares.
//
// One file per title. A fingerprint of the translation code, its compilers and
// the translator's settings heads it: a file made by a build that translates
// differently, or with other settings, is discarded. Records are appended as shaders are translated; a record cut short
// (the app stopped while writing it) is dropped when the file is next opened.
class MetalShaderLibraryCache {
 public:
  struct Key {
    uint64_t low = 0;
    uint64_t high = 0;
    bool operator==(const Key& other) const {
      return low == other.low && high == other.high;
    }
  };

  struct Entry {
    std::vector<uint8_t> metallib;
    std::string entry_point_name;
    // DxilShader::DxilTranslation::used_buffer_mask of the translation.
    uint32_t used_buffer_mask = ~uint32_t(0);
    std::vector<SpirvShader::TextureBinding> texture_bindings;
    std::vector<SpirvShader::SamplerBinding> sampler_bindings;
  };

  ~MetalShaderLibraryCache() { Close(); }

  // Reads the file at |path|, or starts it when it is missing or was made with
  // another |fingerprint|. Closes any file open before.
  void Open(const std::filesystem::path& path, const std::string& fingerprint);
  void Close();
  bool is_open() const {
    std::lock_guard<std::mutex> lock(mutex_);
    return file_ != nullptr;
  }

  // Identifies the translation of |translation|'s shader: its microcode, the
  // host modification and the memory export specialization.
  static Key MakeKey(const Shader::Translation& translation);

  // Thread-safe.
  bool Find(const Key& key, Entry& entry_out);
  // |shader| gives the bindings; its translation must have published them.
  void Store(const Key& key, const std::vector<uint8_t>& metallib,
             const std::string& entry_point_name, uint32_t used_buffer_mask,
             const SpirvShader& shader);

  // A fingerprint of what the stored libraries depend on: the translation
  // sources and compilers (XE_METAL_SHADER_CACHE_SOURCE, generated by
  // shader_cache_version.cmake), the Metal shader converter's build, the GPU and
  // Metal options, and the |translator| description the caller gives.
  static std::string MakeFingerprint(const std::string& translator);

  uint32_t hits() const;
  uint32_t misses() const;

 private:
  struct KeyHash {
    size_t operator()(const Key& key) const { return size_t(key.low); }
  };
  struct Location {
    size_t entry_point_offset;
    uint32_t entry_point_length;
    size_t bindings_offset;
    uint32_t texture_binding_count;
    uint32_t sampler_binding_count;
    size_t metallib_offset;
    uint32_t metallib_length;
    uint32_t used_buffer_mask;
  };

  mutable std::mutex mutex_;
  std::FILE* file_ = nullptr;
  // The records read at Open. Records stored later aren't looked up: the
  // translation they came from stays loaded for the rest of the run.
  std::vector<uint8_t> data_;
  std::unordered_map<Key, Location, KeyHash> locations_;
  std::unordered_map<Key, bool, KeyHash> stored_;
  uint32_t hits_ = 0;
  uint32_t misses_ = 0;
};

}  // namespace metal
}  // namespace gpu
}  // namespace xe

#endif  // XENIA_GPU_METAL_METAL_SHADER_LIBRARY_CACHE_H_
